#!/usr/bin/env python3
"""Generate/check the offline Godot catalog from the reviewed v2 design JSON."""
import argparse
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'prototypes/swarm-flight/region_game/growth_catalog_data.gd'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--source', type=Path, help='Path to the design JSON when the design branch is unavailable.')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
design_path = 'docs/design/honey-growth-tree-v2.json'
design_commit = 'd09794c68e48e04bd6eee1cf6e8d3504617f2290'
if args.source:
    source = args.source.read_bytes()
elif (ROOT / design_path).is_file():
    source = (ROOT / design_path).read_bytes()
else:
    result = subprocess.run(['git', '-C', str(ROOT), 'show', f'{design_commit}:{design_path}'],
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if result.returncode:
        parser.error('Provide --source from design PR #375 or fetch its reviewed commit.')
    source = result.stdout
catalog = json.loads(source)
# Include just the fields used by the in-game book. Regular gameplay owns its
# original fourteen prices, inventory and purchases.
fields = ['cells', 'ranks', 'branches', 'stages']
result = {key: catalog[key] for key in fields}
for rank in result['ranks']:
    rank.pop('effect', None)
    rank.pop('status', None)
body = 'extends RefCounted\n## Generated by tools/sync_honey_native_growth_catalog.py from Honey v2.\n'
body += 'const SOURCE_SHA256 := "' + hashlib.sha256(source).hexdigest() + '"\n'
body += 'const DATA := ' + json.dumps(result, ensure_ascii=False, indent='\t') + '\n'
if args.check:
    if TARGET.read_text() != body:
        raise SystemExit('The packaged growth catalog differs from its design source.')
    print('Packaged growth catalog matches', hashlib.sha256(source).hexdigest())
else:
    TARGET.write_text(body)
